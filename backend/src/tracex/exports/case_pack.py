"""TRACE-X Canonical JSON Case Pack Exporter.
Serializes case evidence, trace results, recommendations, and decisions
with a deterministic SHA256 content hash.
"""
import hashlib
import json
from datetime import datetime, timezone
from typing import Dict, Any
from sqlalchemy.orm import Session

from tracex.repositories.db import Case, Complaint, StoredTraceRun, RecommendationDraft, User


def generate_case_export(db: Session, case_id: str, exporter: User) -> Dict[str, Any]:
    case = db.query(Case).filter(Case.id == case_id).first()
    if not case:
        raise ValueError("Case not found")

    complaint = db.query(Complaint).filter(Complaint.id == case.complaint_id).first()
    trace_run = db.query(StoredTraceRun).filter(StoredTraceRun.case_id == case.id).order_by(StoredTraceRun.created_at.desc()).first()
    recommendation = db.query(RecommendationDraft).filter(RecommendationDraft.case_id == case.id).order_by(RecommendationDraft.created_at.desc()).first()

    raw_trace_json = json.loads(trace_run.result_json) if trace_run else None

    export_payload = {
        "export_metadata": {
            "version": "1.0.0",
            "exported_at": datetime.now(timezone.utc).isoformat(),
            "exported_by": {
                "id": exporter.id,
                "username": exporter.username,
                "role": exporter.role,
            },
            "is_synthetic": True,
            "disclaimer": "This document contains synthetic data and recommendations generated by TRACE-X. It does not constitute an automated legal freeze or direct banking action."
        },
        "case": {
            "id": case.id,
            "status": case.status,
            "disposition": case.disposition,
            "created_at": case.created_at.isoformat() if case.created_at else None,
        },
        "complaint": {
            "id": complaint.id if complaint else None,
            "victim_account": complaint.victim_account if complaint else None,
            "disputed_transaction_ref": complaint.disputed_transaction_ref if complaint else None,
            "disputed_amount": str(complaint.disputed_amount) if complaint else None,
            "reported_time": complaint.reported_time.isoformat() if complaint and complaint.reported_time else None,
            "channel": complaint.channel if complaint else None,
            "match_status": complaint.match_status if complaint else None,
        },
        "trace": raw_trace_json,
        "recommendation": {
            "id": recommendation.id if recommendation else None,
            "status": recommendation.status if recommendation else None,
            "author_id": recommendation.author_id if recommendation else None,
            "justification": recommendation.justification if recommendation else None,
            "total_recommended_amount": str(recommendation.total_recommended_amount) if recommendation else None,
            "selected_accounts": json.loads(recommendation.selected_accounts_json) if recommendation else [],
            "decided_by_id": recommendation.decided_by_id if recommendation else None,
            "decision_reason": recommendation.decision_reason if recommendation else None,
            "decided_at": recommendation.decided_at.isoformat() if recommendation and recommendation.decided_at else None,
            "document_hash": recommendation.document_hash if recommendation else None,
        } if recommendation else None,
    }

    # Canonical hash
    canonical_bytes = json.dumps(export_payload, sort_keys=True, default=str).encode("utf-8")
    content_hash = hashlib.sha256(canonical_bytes).hexdigest()
    export_payload["export_metadata"]["content_hash"] = content_hash

    return export_payload
